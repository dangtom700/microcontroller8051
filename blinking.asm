; This program is used to control PWM of a device
; PWM is controlled by forcing the device to work % of the cycle and idle in (1-%)

ORG 000H
	start:
		JB P2.3, CASE1XX
		JNB P2.3, CASE0XX
	CASE0XX: ;0XX
		JB P2.4, CASE01X
		JNB P2.4, CASE00X
	CASE1XX: ;1XX
		JB P2.4, CASE11X
		JNB P2.4, CASE10X
	CASE00X: ;00X
		JB P2.5, DC10 ; 001
		JNB P2.5, DC0 ; 000
	CASE01X: ;01X
		JB P2.5, DC40 ; 011
		JNB P2.5, DC30 ; 010
	CASE10X: ;10X
		JB P2.5, DC70 ; 101
		JNB P2.5, DC50 ; 100
	CASE11X:
		JB P2.5, DC100 ; 111
		JNB P2.5, DC80 ; 110
		JMP start
		

	;DUTY CYCLES DEFINED
	DC0:
		CLR P2.6
		JMP start
	DC10:
			SETB P2.6
			ACALL DELAY100u
			CLR P2.6
			MOV R1, #9
		HERE10: ACALL DELAY100u
			DJNZ R1, HERE10
			JMP start
	DC30:
			SETB P2.6
			MOV R1, #3
		HERE301: 
			ACALL DELAY100u
			DJNZ R1, HERE501
			CLR P2.6
			MOV R1, #7
		HERE302: 
			ACALL DELAY100u
			DJNZ R1, HERE502
			JMP start
	DC40:
			SETB P2.6
			MOV R1, #4
		HERE401: 
			ACALL DELAY100u
			DJNZ R1, HERE501
			CLR P2.6
			MOV R1, #6
		HERE402: 
			ACALL DELAY100u
			DJNZ R1, HERE502
			JMP start
	DC50:
			SETB P2.6
			MOV R1, #5
		HERE501: 
			ACALL DELAY100u
			DJNZ R1, HERE501
			CLR P2.6
			MOV R1, #5
		HERE502: 
			ACALL DELAY100u
			DJNZ R1, HERE502
			JMP start
	DC70:
			SETB P2.6
			MOV R1, #7
		HERE701: 
			ACALL DELAY100u
			DJNZ R1, HERE501
			CLR P2.6
			MOV R1, #3
		HERE702: 
			ACALL DELAY100u
			DJNZ R1, HERE502
			JMP start
	DC80:
			SETB P2.6
			MOV R1, #8
		HERE801: 
			ACALL DELAY100u
			DJNZ R1, HERE501
			CLR P2.6
			MOV R1, #2
		HERE802: 
			ACALL DELAY100u
			DJNZ R1, HERE502
			JMP start
	DC100:
			SETB P2.6
			MOV R1, #10
		HERE1001: 
			ACALL DELAY100u
			DJNZ R1, HERE501
			CLR P2.6
			MOV R1, #0
		HERE1002: 
			ACALL DELAY100u
			DJNZ R1, HERE502
			JMP start
;DELAY DEFINED
DELAY100u: 
	MOV R2,#100
	HERE:
	NOP
	DJNZ R2,HERE
	RET
END